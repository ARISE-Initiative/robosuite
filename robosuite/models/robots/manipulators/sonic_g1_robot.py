"""SonicG1: 29-DOF Unitree G1 (legs, 3-DOF waist, 7-DOF arms) with Dex3 grippers, driven by the
SONIC whole-body controller through the SONIC_WBC composite controller.

Assets are generated by robosuite/scripts/build_sonic_g1_assets.py from SONIC's G1 model."""
import numpy as np

from robosuite.models.robots.manipulators.legged_manipulator_model import LeggedManipulatorModel
from robosuite.utils.mjcf_utils import xml_path_completion

# SonicG1 -> LeggedRobot is registered in robosuite/robots/__init__.py ROBOT_CLASS_MAPPING;
# @register_robot_class would import robosuite.robots from here, which is a circular import.


class SonicG1(LeggedManipulatorModel):
    """29-DOF G1 with a free-floating base and bimanual Dex3 grippers."""

    arms = ["right", "left"]

    def __init__(self, idn=0):
        super().__init__(xml_path_completion("robots/sonic_g1/robot.xml"), idn=idn)
        # The pelvis is authored at its standing height; zero the base offset so that
        # base_xpos_offset z is the height the env places the pelvis at.
        self._base_offset = np.zeros(3)

    @property
    def default_base(self):
        # NullBase keeps the pelvis freejoint: SONIC controls a true 6-DOF floating base
        return "NullBase"

    @property
    def default_gripper(self):
        return {"right": "SonicDex3RightGripper", "left": "SonicDex3LeftGripper"}

    @property
    def default_controller_config(self):
        return {"right": "default_sonic_g1", "left": "default_sonic_g1"}

    @property
    def init_qpos(self):
        # SONIC's deployed default pose (the C++ holds it before policy control starts), in this
        # robot's joint order
        return np.array(
            [
                -0.312,
                0.0,
                0.0,
                0.669,
                -0.363,
                0.0,
                -0.312,
                0.0,
                0.0,
                0.669,
                -0.363,
                0.0,
                0.0,
                0.0,
                0.0,
                0.2,
                0.2,
                0.0,
                0.6,
                0.0,
                0.0,
                0.0,
                0.2,
                -0.2,
                0.0,
                0.6,
                0.0,
                0.0,
                0.0,
            ]
        )

    @property
    def base_xpos_offset(self):
        STAND_Z = 0.793  # pelvis standing height
        return {
            "bins": (-0.5, -0.1, STAND_Z),
            "empty": (-0.29, 0, STAND_Z),
            "table": lambda table_length: (-0.26 - table_length / 2, 0, STAND_Z),
        }

    @property
    def top_offset(self):
        return np.array((0, 0, 1.0))

    @property
    def _horizontal_radius(self):
        return 0.5

    @property
    def arm_type(self):
        return "bimanual"

    @property
    def _eef_name(self):
        return {"right": "right_eef", "left": "left_eef"}

    @staticmethod
    def _right_first(names):
        # robosuite gives the first half of the arm joints/actuators to the "right" arm, but the
        # model lists the left arm first. arm_joints and arm_actuators must use the same order.
        right = [name for name in names if any(key in name for key in ("r_shoulder", "r_elbow", "r_wrist"))]
        left = [name for name in names if any(key in name for key in ("l_shoulder", "l_elbow", "l_wrist"))]
        return right + left

    @property
    def arm_joints(self):
        return self._right_first(super().arm_joints)

    @property
    def arm_actuators(self):
        return self._right_first(super().arm_actuators)
